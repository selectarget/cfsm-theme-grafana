export function generateMockHistory(hours: number = 24): HistoryMetricRow[] {
  const points = Math.min(120, Math.max(30, Math.floor(hours * 10)));
  const stepMs = (hours * 3600 * 1000) / points;
  const startTime = Date.now() - hours * 3600 * 1000;
  
  const list: HistoryMetricRow[] = [];
  let currentCpu = 15;
  let currentRam = 1400;
  
  for (let i = 0; i < points; i++) {
    const ts = startTime + i * stepMs;
    currentCpu = Math.max(5, Math.min(85, currentCpu + (Math.random() * 10 - 5)));
    currentRam = Math.max(1000, Math.min(3200, currentRam + (Math.random() * 100 - 50)));
    
    list.push({
      timestamp: ts,
      cpu: parseFloat(currentCpu.toFixed(1)),
      ram_used: Math.round(currentRam),
      ram_total: 4096,
      net_in_speed: Math.round(1024 * (150 + Math.sin(i / 5) * 80 + Math.random() * 50)),
      net_out_speed: Math.round(1024 * (300 + Math.cos(i / 5) * 120 + Math.random() * 80)),
      disk_read_bps: Math.round(1024 * (50 + Math.random() * 200)),
      disk_write_bps: Math.round(1024 * (30 + Math.random() * 150)),
      disk: {
        read_bps: Math.round(1024 * (50 + Math.random() * 200)),
        write_bps: Math.round(1024 * (30 + Math.random() * 150)),
        read_iops: Math.round(10 + Math.random() * 30),
        write_iops: Math.round(5 + Math.random() * 20),
        await_ms: parseFloat((0.8 + Math.random() * 1.2).toFixed(2)),
        util: parseFloat((2 + Math.random() * 6).toFixed(1))
      }
    });
  }
  return list;
}
